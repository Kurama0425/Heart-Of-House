import { test, expect } from '@playwright/test';
test('kitchen, ingredient, recipe and shift workflows persist', async ({ page }) => {
  await page.goto('/');
  const kitchen = page.locator('#restaurant-setup');
  await expect(kitchen.getByLabel('Active kitchen')).toBeVisible();
  await kitchen.getByLabel('Active kitchen').selectOption('');
  const name = `Browser Kitchen ${Date.now()}`;
  await kitchen.getByLabel('Restaurant name').fill(name);
  await kitchen.getByRole('button', { name: 'Create restaurant', exact: true }).click();
  await expect(kitchen.getByLabel('Active kitchen')).toContainText(name);
  const ingredients = page.locator('#ingredients');
  await ingredients.getByLabel('Name', { exact: true }).fill('Flour');
  await ingredients.getByLabel('Purchase unit', { exact: true }).fill('lb');
  await ingredients.getByLabel('Purchase quantity').fill('25');
  await ingredients.getByLabel('Purchase price ($, optional)').fill('18.50');
  await ingredients.getByRole('button', { name: 'Save ingredient' }).click();
  await expect(ingredients.getByRole('cell', { name: 'Flour', exact: true })).toBeVisible();
  const recipes = page.locator('#recipes');
  await recipes.getByLabel('Recipe name').fill('Dough');
  await recipes.getByLabel('Batch yield').fill('8');
  await recipes.getByLabel('Instructions').fill('Mix and knead.');
  await recipes.getByRole('button', { name: 'Add ingredient', exact: true }).click();
  await recipes.getByLabel('Ingredient 1', { exact: true }).selectOption({ label: 'Flour' });
  await recipes.getByLabel('Quantity', { exact: true }).fill('16');
  await recipes.getByLabel('Unit', { exact: true }).fill('oz');
  await recipes.getByRole('button', { name: 'Save recipe', exact: true }).click();
  await expect(recipes.getByText('Batch cost: $0.74', { exact: true })).toBeVisible();
  await recipes.getByRole('button', { name: 'Edit recipe', exact: true }).click();
  await recipes.getByLabel('Quantity', { exact: true }).fill('2');
  await recipes.getByLabel('Unit', { exact: true }).fill('lb');
  await recipes.getByRole('button', { name: 'Save changes', exact: true }).click();
  await expect(recipes.getByText('Batch cost: $1.48', { exact: true })).toBeVisible();
  await ingredients.getByRole('button', { name: 'Edit Flour', exact: true }).click();
  await ingredients.getByLabel('Purchase price ($, optional)').fill('25');
  await ingredients.getByRole('button', { name: 'Save ingredient' }).click();
  await expect(recipes.getByText('Batch cost: $2.00', { exact: true })).toBeVisible();
  await kitchen.getByLabel('Restaurant name').fill(name + ' Updated');
  await kitchen.getByRole('button', { name: 'Save kitchen', exact: true }).click();
  const prep = page.locator('#prep');
  await prep.getByLabel('Tasks—one per line').fill('Portion dough');
  await prep.getByRole('button', { name: 'Create prep list', exact: true }).click();
  await prep.getByRole('checkbox', { name: 'Portion dough' }).check();
  await expect(prep.getByRole('checkbox')).toBeEnabled();
  const checklists = page.locator('#checklists');
  await checklists.getByLabel('Tasks—one per line').fill('Stock line');
  await checklists.getByRole('button', { name: 'Save template', exact: true }).click();
  await checklists.getByRole('button', { name: 'Start fresh checklist', exact: true }).click();
  await checklists.getByRole('checkbox', { name: 'Stock line' }).check();
  await expect(checklists.getByRole('checkbox')).toBeEnabled();
  await page.reload();
  await expect(kitchen.getByLabel('Restaurant name')).toHaveValue(name + ' Updated');
  await expect(prep.getByRole('checkbox', { name: 'Portion dough' })).toBeChecked();
  await expect(checklists.getByRole('checkbox', { name: 'Stock line' })).toBeChecked();
  await expect(ingredients.getByRole('cell', { name: '$25.00', exact: true })).toBeVisible();
  await recipes.getByLabel('Saved recipes').selectOption({ label: 'Dough — 8.0000 portion' });
  await expect(recipes.getByText('Batch cost: $2.00', { exact: true })).toBeVisible();
});
